"""Does the size of VaVAM's left drift follow the route-command threshold?

d1_queue runs each of the mirror test's 20 plain configs (10 drift-heavy
scenes x 2 seeds) at VaVAM's own 2 Hz rhythm under three command rules:
AlpaSim's (RIGHT once the route 20 m ahead is 3 m to the right), 2 m (VaVAM's
NeuroNCAP evaluation) and 1 m. If the drift settles where the corrective
command first fires, it shrinks with the threshold; a lean the command cannot
correct stays. For every kept run: the ego's signed offset from the recorded
path (left positive, drift_analysis.signed_offset) 3 s and 5 s after the
hand-off and at the end, and whether it failed.

Writes research/COMMAND_RULE.md and research/command_rule.json.

    uv run python research/harness/command_rule_report.py
"""

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from drift_analysis import run_offsets
from read_state import DEFAULT_COMMAND_RULE, ROOT, command_rule_request, load_entry, queue_entries

QUEUE = ROOT / "research" / "harness" / "d1_queue"
SIDE_M = 0.5


def main() -> int:
    by_rule: dict[float, list[dict]] = {}
    for path in queue_entries(QUEUE):
        entry = load_entry(path)
        if entry["resolution"] != "ACCEPT" or "quarantine" in entry:
            continue
        threshold = command_rule_request(entry["config"])["threshold_m"]
        offsets = run_offsets(ROOT / entry["run_dir"])
        by_rule.setdefault(threshold, []).append({
            "run": entry["name"],
            "at_3s": offsets["after"].get(3.0),
            "at_5s": offsets["after"].get(5.0),
            "at_end": offsets["at_end"],
            "failed": offsets["failed"],
        })
    summary = {}
    for threshold, runs in sorted(by_rule.items(), reverse=True):
        row = {"runs": len(runs), "failed": sum(r["failed"] for r in runs)}
        for key in ("at_3s", "at_5s", "at_end"):
            values = [r[key] for r in runs if r[key] is not None]
            row[key] = {
                "median": float(np.median(values)) if values else None,
                "left": sum(v > SIDE_M for v in values),
                "right": sum(v < -SIDE_M for v in values),
                "n": len(values),
            }
        summary[threshold] = row
    (ROOT / "research" / "command_rule.json").write_text(
        json.dumps({"summary": summary, "runs": by_rule}, indent=1) + "\n"
    )
    default = DEFAULT_COMMAND_RULE["threshold_m"]
    lines = [
        "# Drift against the route-command threshold",
        "",
        "Generated by `harness/command_rule_report.py` from `harness/d1_queue`: the",
        "mirror test's 20 plain configs at 2 Hz control, under three command",
        f"thresholds (route 20 m ahead; {default:g} m is AlpaSim's VaVAM default, 2 m",
        "VaVAM's NeuroNCAP evaluation). Offsets from the recorded path, left",
        f"positive; left or right means more than {SIDE_M} m.",
        "",
        "| threshold | kept runs | failed | median +3 s | median +5 s | median at end | ended left / right |",
        "|---|---|---|---|---|---|---|",
    ]
    fmt = lambda v: "-" if v is None else f"{v:+.2f} m"
    for threshold, row in summary.items():
        end = row["at_end"]
        lines.append(
            f"| {threshold:g} m | {row['runs']} | {row['failed']} | {fmt(row['at_3s']['median'])} "
            f"| {fmt(row['at_5s']['median'])} | {fmt(end['median'])} | {end['left']} / {end['right']} |"
        )
    (ROOT / "research" / "COMMAND_RULE.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
