"""Where are a study's hardest cases, and where did each method look?

Under replayed traffic a setting's outcome barely depends on the seed (FACTS,
"Replicates under replayed traffic are nearly deterministic"), so every kept
run of a study, from every arm, pools into one map of the setting space. A
setting is hard when its pooled failure rate is surely above the goal's
high_min (goals.rate_range, 90%). A setting's distance from the recorded one
is the number of grid steps (knobs.SCENARIO) summed over the varied knobs;
0 is the recording as it happened.

Per method (all its arms pooled), from its own planned runs (not the inner
loop's retries): how far from the recording it looked, how many settings and
scenes it tried, the share of its runs spent on hard settings, and how many
of the study's hard scenes it touched at all. Writes research/WHERE.md and
research/where.json.

    uv run python research/harness/where_found.py [study ...]
"""

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))

from compare_proposers import arms, proposer_of
from goals import rate_range
from knobs import SCENARIO, UNVARIED
from outer import history
from read_state import ROOT

STUDIES = ROOT / "research" / "studies"
DEFAULT = (
    "pedestrian_ego_speed",
    "lead_vehicle",
    "cut_in_merge",
    "pedestrian_ego_speed_2hz",
    "lead_vehicle_2hz",
    "cut_in_merge_2hz",
)


def distance(setting: dict, varied: tuple) -> int:
    """Grid steps from the recorded setting, summed over the varied knobs."""
    return sum(
        abs(SCENARIO[k].index(setting[k]) - SCENARIO[k].index(UNVARIED[k]))
        for k in varied
    )


def study_map(study: Path) -> dict:
    plan = json.loads((study / "plan.json").read_text(encoding="utf-8"))["plan"]
    varied = tuple(plan["vary"])
    high_min = plan["goal"]["high_min"]
    by_arm = {arm: history(folder / "queue", varied) for arm, folder in arms(study).items()}
    cells = defaultdict(lambda: [0, 0])
    for rows in by_arm.values():
        for row in rows:
            if row["verdict"] == "kept":
                key = (row["scene_id"], *(row[k] for k in varied))
                cells[key][0] += 1
                cells[key][1] += row["failed"]
    hard = {
        key
        for key, (runs, failed) in cells.items()
        if rate_range(failed, runs)[0] > high_min
    }
    hard_scenes = {key[0] for key in hard}
    as_setting = lambda key: dict(zip(varied, key[1:]))
    nominal_fails = {key[0] for key in hard if distance(as_setting(key), varied) == 0}
    methods = defaultdict(lambda: {"arms": 0, "runs": [], "settings": set(), "scenes": set()})
    for arm, rows in by_arm.items():
        m = methods[proposer_of(arm)]
        m["arms"] += 1
        for row in rows:
            key = (row["scene_id"], *(row[k] for k in varied))
            m["runs"].append(key)
            m["settings"].add(key)
            m["scenes"].add(key[0])
    report = {
        "varied": list(varied),
        "settings_tried": len(cells),
        "hard_settings": len(hard),
        "hard_scenes": len(hard_scenes),
        "scenes": len(plan["scenes"]),
        "hard_scenes_failing_as_recorded": len(nominal_fails),
        "hard_distance": dict(
            sorted(Counter(distance(as_setting(k), varied) for k in hard).items())
        ),
        "hard_examples": [
            {"scene": k[0][7:15], **as_setting(k), "runs": cells[k][0], "failed": cells[k][1]}
            for k in sorted(hard)
        ],
        "methods": {},
    }
    for name, m in sorted(methods.items()):
        dist = np.array([distance(as_setting(k), varied) for k in m["runs"]])
        report["methods"][name] = {
            "arms": m["arms"],
            "runs": len(m["runs"]),
            "mean_distance": round(float(dist.mean()), 2) if len(dist) else None,
            "share_at_recording": round(float(np.mean(dist == 0)), 2) if len(dist) else None,
            "share_2_or_more_steps": round(float(np.mean(dist >= 2)), 2) if len(dist) else None,
            "settings_per_arm": round(len(m["settings"]) / m["arms"], 1),
            "share_of_runs_on_hard": round(
                sum(k in hard for k in m["runs"]) / max(len(m["runs"]), 1), 2
            ),
            "hard_scenes_touched": len({k[0] for k in m["settings"] & hard}),
        }
    return report


def main() -> int:
    names = sys.argv[1:] or [s for s in DEFAULT if (STUDIES / s / "plan.json").exists()]
    report = {name: study_map(STUDIES / name) for name in names}
    (ROOT / "research" / "where.json").write_text(json.dumps(report, indent=1) + "\n")
    lines = [
        "# Where the hardest cases are, and where each method looked",
        "",
        "Generated by `harness/where_found.py`. Every kept run of a study, from",
        "every arm, pooled per setting (outcomes under replay barely depend on",
        "the seed). Hard: pooled failure rate surely above the goal's high_min",
        "(90%). Distance: grid steps from the recorded setting, summed over the",
        "varied knobs. A method's numbers pool all its arms and count every run",
        "it queued, retries included.",
        "",
    ]
    for name, r in report.items():
        lines += [
            f"## {name}",
            "",
            f"{r['settings_tried']} settings tried by any method; {r['hard_settings']} hard, "
            f"on {r['hard_scenes']} of {r['scenes']} scenes "
            f"({r['hard_scenes_failing_as_recorded']} of them hard as recorded). "
            "Hard settings by distance from the recording: "
            + ", ".join(f"{d} steps: {n}" for d, n in r["hard_distance"].items())
            + ".",
            "",
            "| method | arms | runs | mean distance | at the recording | 2+ steps away "
            "| settings per arm | runs on hard settings | hard scenes touched |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for m, v in r["methods"].items():
            lines.append(
                f"| {m} | {v['arms']} | {v['runs']} | {v['mean_distance']} "
                f"| {v['share_at_recording']:.0%} | {v['share_2_or_more_steps']:.0%} "
                f"| {v['settings_per_arm']} | {v['share_of_runs_on_hard']:.0%} "
                f"| {v['hard_scenes_touched']} of {r['hard_scenes']} |"
            )
        lines.append("")
    (ROOT / "research" / "WHERE.md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
